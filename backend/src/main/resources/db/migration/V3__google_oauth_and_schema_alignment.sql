-- and align TIMESTAMP columns with Hibernate 6 Instant mapping (DATETIME(6)) for ddl-auto=validate.
-- Separate ALTER TABLE statements (without AFTER clauses) ensure full TiDB & MySQL 8 compatibility.

ALTER TABLE users MODIFY COLUMN password VARCHAR(255) NULL;

ALTER TABLE users ADD COLUMN auth_provider VARCHAR(30) NOT NULL DEFAULT 'LOCAL';
ALTER TABLE users ADD COLUMN google_sub VARCHAR(255) NULL;
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE users ADD CONSTRAINT uk_users_google_sub UNIQUE (google_sub);
ALTER TABLE users ADD INDEX idx_users_google_sub (google_sub);

ALTER TABLE users MODIFY COLUMN created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);
ALTER TABLE users MODIFY COLUMN updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6);

