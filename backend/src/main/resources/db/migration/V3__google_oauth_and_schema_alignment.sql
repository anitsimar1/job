-- Support Google OAuth 2.0 accounts (nullable password, google_sub, auth_provider, email_verified)
-- and align TIMESTAMP columns with Hibernate 6 Instant mapping (DATETIME(6)) for ddl-auto=validate.

ALTER TABLE users
    MODIFY COLUMN password VARCHAR(255) NULL,
    ADD COLUMN auth_provider VARCHAR(30) NOT NULL DEFAULT 'LOCAL' AFTER profile_image,
    ADD COLUMN google_sub VARCHAR(255) NULL AFTER auth_provider,
    ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE AFTER google_sub,
    ADD CONSTRAINT uk_users_google_sub UNIQUE (google_sub),
    ADD INDEX idx_users_google_sub (google_sub),
    MODIFY COLUMN created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    MODIFY COLUMN updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6);

ALTER TABLE jobs
    MODIFY COLUMN created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    MODIFY COLUMN updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6);

ALTER TABLE resumes
    MODIFY COLUMN uploaded_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);

ALTER TABLE applications
    MODIFY COLUMN applied_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    MODIFY COLUMN updated_at DATETIME(6) NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6);

ALTER TABLE saved_jobs
    MODIFY COLUMN saved_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);

ALTER TABLE revoked_tokens
    MODIFY COLUMN expires_at DATETIME(6) NOT NULL,
    MODIFY COLUMN revoked_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);
